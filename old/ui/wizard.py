# ui/wizard.py
"""
First-run setup wizard.

Shown once when canoe_suite.cfg is absent or lacks the
'setup_complete: true' key.  Writes a valid canoe_suite.cfg
on finish so the main window loads it on next start.

No business logic — just reads paddler weights and DB path
from the user then serialises them to YAML.
"""
from __future__ import annotations

import os
from pathlib import Path

from PyQt6.QtCore import Qt
from PyQt6.QtGui import QFont
from PyQt6.QtWidgets import (
    QDialog, QVBoxLayout, QHBoxLayout, QLabel, QLineEdit,
    QPushButton, QFileDialog, QGroupBox, QGridLayout,
    QWidget, QStackedWidget, QFrame,
)

_CFG_TEMPLATE = """\
# canoe_suite.cfg  —  generated by first-run wizard {date}
# Edit any value here; restart the app to pick up changes.

setup_complete: true

structural:
  factor_of_safety: 1.5
  dynamic_load_factor: 1.2
  maneuver_coupling_k: 0.5
  thickness_options_in: [0.375, 0.5, 0.625, 0.75]
  freeboard_min_in: 6.0

crew:
  race_4_person_lbs: [{p4}]
  race_2_person_lbs: [{p2}]
  paddler_power_w: 75.0

mix:
  min_density_pcf: 60.0
  max_density_pcf: 80.0
  db_path: "{db_path}"

water:
  rho_kg_m3: 998.0
  nu_m2_s: 1.139e-6
"""


def needs_wizard(cfg_path: str) -> bool:
    """Return True when the wizard should be shown."""
    if not os.path.exists(cfg_path):
        return True
    try:
        import yaml
        with open(cfg_path) as fh:
            data = yaml.safe_load(fh) or {}
        return not data.get("setup_complete", False)
    except Exception:
        return False


class _NavBar(QWidget):
    """Simple step indicator (1 / 2 / 3)."""

    def __init__(self, n_steps: int, parent=None):
        super().__init__(parent)
        self._n = n_steps
        self._labels: list[QLabel] = []
        lay = QHBoxLayout(self)
        lay.setContentsMargins(0, 0, 0, 0)
        lay.addStretch()
        for i in range(n_steps):
            lbl = QLabel(str(i + 1))
            lbl.setFixedSize(28, 28)
            lbl.setAlignment(Qt.AlignmentFlag.AlignCenter)
            lbl.setStyleSheet(
                "border-radius: 14px; border: 1px solid #555; color: #888;")
            self._labels.append(lbl)
            lay.addWidget(lbl)
            if i < n_steps - 1:
                sep = QLabel("—")
                sep.setStyleSheet("color: #555;")
                lay.addWidget(sep)
        lay.addStretch()
        self.set_step(0)

    def set_step(self, idx: int):
        for i, lbl in enumerate(self._labels):
            if i == idx:
                lbl.setStyleSheet(
                    "border-radius: 14px; background: #00d2ff;"
                    " color: #000; font-weight: bold;")
            elif i < idx:
                lbl.setStyleSheet(
                    "border-radius: 14px; background: #1a6a80;"
                    " color: #aaa;")
            else:
                lbl.setStyleSheet(
                    "border-radius: 14px; border: 1px solid #555;"
                    " color: #555;")


class FirstRunWizard(QDialog):
    """3-page wizard that writes canoe_suite.cfg on finish."""

    def __init__(self, cfg_path: str, parent=None):
        super().__init__(parent)
        self._cfg_path = cfg_path
        self._step = 0
        self.setWindowTitle("JAGUAR — First-time Setup")
        self.setMinimumWidth(540)
        self.setModal(True)

        root = QVBoxLayout(self)
        root.setSpacing(12)

        # Header
        hdr = QLabel("Welcome to the ASCE Canoe Engineering Suite")
        hdr.setFont(QFont("Segoe UI", 14, QFont.Weight.Bold))
        hdr.setAlignment(Qt.AlignmentFlag.AlignCenter)
        hdr.setStyleSheet("color: #00d2ff; padding: 6px;")
        root.addWidget(hdr)

        self._nav = _NavBar(3)
        root.addWidget(self._nav)

        sep = QFrame()
        sep.setFrameShape(QFrame.Shape.HLine)
        sep.setStyleSheet("color: #333;")
        root.addWidget(sep)

        self._stack = QStackedWidget()
        root.addWidget(self._stack, stretch=1)

        self._stack.addWidget(self._make_page_welcome())
        self._stack.addWidget(self._make_page_crew())
        self._stack.addWidget(self._make_page_db())

        # Navigation buttons
        btn_row = QHBoxLayout()
        root.addLayout(btn_row)
        self._back_btn = QPushButton("← Back")
        self._back_btn.setEnabled(False)
        self._back_btn.clicked.connect(self._go_back)
        btn_row.addWidget(self._back_btn)
        btn_row.addStretch()
        self._next_btn = QPushButton("Next →")
        self._next_btn.setDefault(True)
        self._next_btn.clicked.connect(self._go_next)
        btn_row.addWidget(self._next_btn)

    # ------------------------------------------------------------------
    # Page builders
    # ------------------------------------------------------------------
    def _make_page_welcome(self) -> QWidget:
        w = QWidget()
        lay = QVBoxLayout(w)
        lay.setContentsMargins(16, 8, 16, 8)
        lay.addStretch()
        msg = QLabel(
            "This short wizard sets up the few options that affect every run.\n\n"
            "You can change any of these later by editing  canoe_suite.cfg  "
            "in the project folder.\n\n"
            "Click  Next  to continue."
        )
        msg.setWordWrap(True)
        msg.setStyleSheet("font-size: 12pt; color: #ccc;")
        lay.addWidget(msg)
        lay.addStretch()
        return w

    def _make_page_crew(self) -> QWidget:
        w = QWidget()
        lay = QVBoxLayout(w)
        lay.setContentsMargins(16, 8, 16, 8)

        lbl = QLabel("Paddler weights (bow → stern)")
        lbl.setStyleSheet("font-size: 11pt; font-weight: bold; color: #ddd;")
        lay.addWidget(lbl)

        grp4 = QGroupBox("4-Person race")
        g4 = QGridLayout(grp4)
        self._w4: list[QLineEdit] = []
        defaults4 = ["160", "150", "170", "160"]
        for i, d in enumerate(defaults4):
            g4.addWidget(QLabel(f"Paddler {i+1} (lb)"), 0, i * 2,
                         alignment=Qt.AlignmentFlag.AlignRight)
            e = QLineEdit(d)
            e.setFixedWidth(70)
            g4.addWidget(e, 0, i * 2 + 1)
            self._w4.append(e)
        lay.addWidget(grp4)

        grp2 = QGroupBox("2-Person race")
        g2 = QGridLayout(grp2)
        self._w2: list[QLineEdit] = []
        defaults2 = ["170", "160"]
        for i, d in enumerate(defaults2):
            g2.addWidget(QLabel(f"Paddler {i+1} (lb)"), 0, i * 2,
                         alignment=Qt.AlignmentFlag.AlignRight)
            e = QLineEdit(d)
            e.setFixedWidth(70)
            g2.addWidget(e, 0, i * 2 + 1)
            self._w2.append(e)
        lay.addWidget(grp2)
        lay.addStretch()
        return w

    def _make_page_db(self) -> QWidget:
        w = QWidget()
        lay = QVBoxLayout(w)
        lay.setContentsMargins(16, 8, 16, 8)

        lbl = QLabel("Mix database location")
        lbl.setStyleSheet("font-size: 11pt; font-weight: bold; color: #ddd;")
        lay.addWidget(lbl)

        note = QLabel(
            "The mix database stores lab results and regression fits.\n"
            "For a shared team drive, point this to a folder on OneDrive\n"
            "or a network share so all team members use the same data."
        )
        note.setWordWrap(True)
        note.setStyleSheet("color: #aaa;")
        lay.addWidget(note)

        default_db = os.path.join(
            os.path.dirname(self._cfg_path), "concrete_mixes.db")
        row = QHBoxLayout()
        self._db_edit = QLineEdit(default_db)
        self._db_edit.setMinimumWidth(320)
        browse = QPushButton("Browse…")
        browse.clicked.connect(self._browse_db)
        row.addWidget(self._db_edit, stretch=1)
        row.addWidget(browse)
        lay.addLayout(row)
        lay.addStretch()
        return w

    # ------------------------------------------------------------------
    # Navigation
    # ------------------------------------------------------------------
    def _go_next(self):
        if self._step < 2:
            self._step += 1
            self._stack.setCurrentIndex(self._step)
            self._nav.set_step(self._step)
            self._back_btn.setEnabled(True)
            if self._step == 2:
                self._next_btn.setText("Finish")
        else:
            self._finish()

    def _go_back(self):
        if self._step > 0:
            self._step -= 1
            self._stack.setCurrentIndex(self._step)
            self._nav.set_step(self._step)
            self._next_btn.setText("Next →")
            self._back_btn.setEnabled(self._step > 0)

    def _browse_db(self):
        path, _ = QFileDialog.getSaveFileName(
            self, "Choose database file location",
            self._db_edit.text(), "SQLite database (*.db)")
        if path:
            self._db_edit.setText(path)

    # ------------------------------------------------------------------
    # Write config
    # ------------------------------------------------------------------
    def _finish(self):
        from datetime import date as _date
        p4 = ", ".join(e.text().strip() or "160" for e in self._w4)
        p2 = ", ".join(e.text().strip() or "160" for e in self._w2)
        db_path = self._db_edit.text().strip().replace("\\", "/")

        content = _CFG_TEMPLATE.format(
            date=_date.today().isoformat(),
            p4=p4,
            p2=p2,
            db_path=db_path,
        )
        with open(self._cfg_path, "w", encoding="utf-8") as fh:
            fh.write(content)
        self.accept()
